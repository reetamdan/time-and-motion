"""The committed RTX A6000 profile (configs/a6000) loads, pins real artifacts, and matches its generator."""

from __future__ import annotations

import importlib.util
import os

import pytest
import yaml

from backend.app.configuration import load_configuration
from backend.app.perception.artifacts import MATCH, HashMemo, runtime_artifact_checks

from .support import PROJECT_ROOT

PROFILE = PROJECT_ROOT / "configs" / "a6000"
ENGINE_DIRS = ("trafficcamnet-smoke", "rt-detr-person-candidate", "rf-detr-person-candidate")


def _missing_engines() -> list[str]:
    """A6000 engines that are absent or still Git LFS pointer files."""
    engines = [path for name in ENGINE_DIRS for path in (PROJECT_ROOT / "models" / name).glob("*_sm86.engine")]
    missing = [str(path.relative_to(PROJECT_ROOT)) for path in engines if path.stat().st_size < 1024]
    return missing if engines else ["models/*/*_sm86.engine"]


_MISSING = _missing_engines()
requires_a6000_engines = pytest.mark.skipif(
    bool(_MISSING) and os.environ.get("AEGIS_REQUIRE_LOCAL_ARTIFACTS") != "1",
    reason=f"A6000 engines not present (git lfs pull): {', '.join(_MISSING)}",
)


def _configure_module():
    spec = importlib.util.spec_from_file_location("a6000_configure", PROJECT_ROOT / "scripts" / "a6000" / "configure.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_profile_loads_with_the_documented_overrides() -> None:
    config = load_configuration(PROFILE, PROJECT_ROOT)
    assert config.models.selected_model == "rt-detr-person-candidate"
    assert config.models.selection_mode == "candidate_evaluation"  # still an unaccepted candidate
    assert config.models.selected.precision == "FP16"
    assert config.camera_map["cam-01"].loop is True
    assert all(model.engine_path.name.endswith("_sm86.engine") for model in config.models.models)
    upstream = load_configuration(PROJECT_ROOT / "configs", PROJECT_ROOT)
    assert upstream.models.selected_model == "trafficcamnet-smoke" and upstream.camera_map["cam-01"].loop is False


def test_every_generated_file_carries_the_do_not_edit_header() -> None:
    for path in [*PROFILE.glob("*.yaml"), *(PROJECT_ROOT / "perception" / "deepstream" / "a6000").glob("*.txt")]:
        assert "GENERATED by scripts/a6000/configure.py" in path.read_text(encoding="utf-8").splitlines()[0], path
    assert sorted(p.name for p in PROFILE.glob("*.yaml")) == sorted(p.name for p in (PROJECT_ROOT / "configs").glob("*.yaml"))
    yaml.safe_load((PROFILE / "models.yaml").read_text(encoding="utf-8"))


@requires_a6000_engines
def test_profile_is_in_sync_with_configs_and_engines() -> None:
    """Editing configs/ without regenerating (or replacing an engine without re-pinning) fails here."""
    assert _configure_module().check() == 0


@requires_a6000_engines
def test_every_selected_artifact_identity_matches() -> None:
    config = load_configuration(PROFILE, PROJECT_ROOT)
    checks = runtime_artifact_checks(config, HashMemo())
    assert {item.name: item.status for item in checks if item.status != MATCH} == {}

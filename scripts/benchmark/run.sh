#!/usr/bin/env bash
# Execute a real local benchmark runner; this wrapper never creates performance measurements.
set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
ROOT="$(cd -- "$SCRIPT_DIR/../.." && pwd -P)"
STAGE=""
STREAMS=""
PROFILE=""
RUN_ID="$(date -u +%Y%m%dT%H%M%SZ)"
WARMUP="${CCTV_BENCHMARK_WARMUP_SECONDS:-120}"
DURATION="${CCTV_BENCHMARK_DURATION_SECONDS:-600}"
DRY_RUN=0

usage() {
  cat <<'USAGE'
Usage: bash scripts/benchmark/run.sh --stage A..H --streams N --profile FILE \
  [--run-id ID] [--warmup-seconds N] [--duration-seconds N] [--dry-run] \
  -- LOCAL_RUNNER [ARGS...]

Defaults follow the initial capacity profile: 120 s warm-up and 600 s measured
steady state. Shorter runs must be labeled engineering runs by the runner; they are
not silently promoted to acceptance. The runner receives:
  CCTV_BENCHMARK_STAGE, CCTV_BENCHMARK_STREAMS, CCTV_BENCHMARK_PROFILE,
  CCTV_BENCHMARK_PROFILE_SHA256, CCTV_BENCHMARK_RUN_ID, CCTV_BENCHMARK_OUTPUT,
  CCTV_BENCHMARK_WARMUP_SECONDS, CCTV_BENCHMARK_DURATION_SECONDS.

It must collect real raw metrics and write summary.json plus report.md in
CCTV_BENCHMARK_OUTPUT. summary.json must conform to summary.schema.json. This wrapper
checks required provenance/result structure but does not invent metrics or decide
acceptance. --dry-run validates inputs only. Omitting a runner is a blocker.
USAGE
}

while (($#)); do
  case "$1" in
    --stage) [[ $# -ge 2 && "$2" =~ ^[A-Ha-h]$ ]] || { echo "ERROR: --stage must be A through H" >&2; exit 64; }; STAGE="${2^^}"; shift 2 ;;
    --streams) [[ $# -ge 2 && "$2" =~ ^[1-9][0-9]*$ ]] || { echo "ERROR: --streams must be a positive integer" >&2; exit 64; }; STREAMS="$2"; shift 2 ;;
    --profile) [[ $# -ge 2 && -n "$2" ]] || { echo "ERROR: --profile requires a file" >&2; exit 64; }; PROFILE="$2"; shift 2 ;;
    --run-id) [[ $# -ge 2 && "$2" =~ ^[A-Za-z0-9._-]+$ ]] || { echo "ERROR: invalid --run-id" >&2; exit 64; }; RUN_ID="$2"; shift 2 ;;
    --warmup-seconds) [[ $# -ge 2 && "$2" =~ ^[0-9]+$ ]] || { echo "ERROR: invalid warm-up duration" >&2; exit 64; }; WARMUP="$2"; shift 2 ;;
    --duration-seconds) [[ $# -ge 2 && "$2" =~ ^[1-9][0-9]*$ ]] || { echo "ERROR: invalid measured duration" >&2; exit 64; }; DURATION="$2"; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    --) shift; break ;;
    -h|--help) usage; exit 0 ;;
    *) echo "ERROR: unknown argument before --: $1" >&2; usage >&2; exit 64 ;;
  esac
done

[[ -n "$STAGE" && -n "$STREAMS" ]] || { echo "ERROR: --stage and --streams are required" >&2; exit 64; }
[[ -n "$PROFILE" && -f "$PROFILE" ]] || { echo "ERROR: --profile must name an installed workload profile" >&2; exit 64; }
if (($# == 0 && ! DRY_RUN)); then
  echo "ERROR: benchmark BLOCKED: supply a real local runner after --; no metrics/report were fabricated." >&2
  exit 64
fi
if ((DRY_RUN && $# > 0)); then echo "ERROR: --dry-run cannot be combined with a runner" >&2; exit 64; fi
case ",1,2,4,6,8," in *,"$STREAMS",*) ;; *) echo "WARNING: $STREAMS is outside the initial 1/2/4/6/8 ladder; document the reason" >&2 ;; esac

PYTHON_BIN="${PYTHON:-}"
if [[ -z "$PYTHON_BIN" ]]; then
  if [[ -x "$ROOT/.venv-wsl/bin/python" ]]; then PYTHON_BIN="$ROOT/.venv-wsl/bin/python";
  elif [[ -x "$ROOT/.venv/bin/python" ]]; then PYTHON_BIN="$ROOT/.venv/bin/python";
  else PYTHON_BIN="$(command -v python3 || command -v python || true)"; fi
fi
command -v -- "$PYTHON_BIN" >/dev/null 2>&1 || { echo "ERROR: project Python not found: $PYTHON_BIN" >&2; exit 2; }
PROFILE="$(cd -- "$(dirname -- "$PROFILE")" && pwd -P)/$(basename -- "$PROFILE")"
OUT="$ROOT/reports/benchmarks/$RUN_ID"
[[ ! -e "$OUT" ]] || { echo "ERROR: refusing to overwrite benchmark directory: $OUT" >&2; exit 1; }
mkdir -p -- "$OUT"
PROFILE_SHA256="$("$PYTHON_BIN" - "$PROFILE" <<'PY'
import hashlib, sys
h = hashlib.sha256()
with open(sys.argv[1], "rb") as handle:
    for chunk in iter(lambda: handle.read(1024 * 1024), b""):
        h.update(chunk)
print(h.hexdigest())
PY
)"
{
  printf 'utc_started=%s\nrun_id=%s\nstage=%s\nstreams=%s\nprofile=%q\nprofile_sha256=%s\nwarmup_seconds=%s\nduration_seconds=%s\n' \
    "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$RUN_ID" "$STAGE" "$STREAMS" "$PROFILE" "$PROFILE_SHA256" "$WARMUP" "$DURATION"
  printf 'note=No performance values are generated by this wrapper.\n'
} >"$OUT/run-metadata.txt"

set +e
"$PYTHON_BIN" "$ROOT/scripts/lib/profile_assets.py" --root "$ROOT" --profile "$PROFILE" \
  --streams "$STREAMS" --output "$OUT/profile-validation.json" >"$OUT/profile-validation.log" 2>&1
PROFILE_RC=$?
set -e
if ((PROFILE_RC != 0)); then
  printf 'Benchmark profile/asset validation failed (exit %d). See %s/profile-validation.log\n' "$PROFILE_RC" "$OUT" >&2
  exit "$PROFILE_RC"
fi

if ((DRY_RUN)); then
  printf 'Benchmark arguments/profile and local media validated. No runner was invoked and no metrics were produced.\n'
  exit 0
fi

export CCTV_BENCHMARK_STAGE="$STAGE" CCTV_BENCHMARK_STREAMS="$STREAMS"
export CCTV_BENCHMARK_PROFILE="$PROFILE" CCTV_BENCHMARK_PROFILE_SHA256="$PROFILE_SHA256"
export CCTV_BENCHMARK_RUN_ID="$RUN_ID" CCTV_BENCHMARK_OUTPUT="$OUT"
export CCTV_BENCHMARK_WARMUP_SECONDS="$WARMUP" CCTV_BENCHMARK_DURATION_SECONDS="$DURATION"
export CCTV_OFFLINE=1 HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 HF_DATASETS_OFFLINE=1 PIP_NO_INDEX=1
printf 'runner:' >>"$OUT/run-metadata.txt"; printf ' %q' "$@" >>"$OUT/run-metadata.txt"; printf '\n' >>"$OUT/run-metadata.txt"
nvidia-smi >"$OUT/nvidia-smi-baseline.log" 2>&1 || printf 'nvidia-smi baseline unavailable; runner must record the limitation\n' >>"$OUT/run-metadata.txt"

set +e
"$@" >"$OUT/runner.log" 2>&1
RUNNER_RC=$?
set -e
printf 'runner_exit_code=%d\nutc_finished=%s\n' "$RUNNER_RC" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" >>"$OUT/run-metadata.txt"
if ((RUNNER_RC != 0)); then
  printf 'Benchmark runner failed (exit %d). See %s/runner.log; no passing result is inferred.\n' "$RUNNER_RC" "$OUT" >&2
  exit "$RUNNER_RC"
fi

"$PYTHON_BIN" - "$OUT" "$RUN_ID" "$STAGE" "$STREAMS" "$PROFILE_SHA256" "$WARMUP" "$DURATION" <<'PY'
import json, sys
from pathlib import Path
out = Path(sys.argv[1])
summary_path = out / "summary.json"
report_path = out / "report.md"
try:
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
except Exception as exc:
    raise SystemExit(f"ERROR: runner exited 0 but summary.json is missing/invalid: {exc}")
if not report_path.is_file() or report_path.stat().st_size == 0:
    raise SystemExit("ERROR: runner did not produce a nonempty report.md")
expected = {"run_id": sys.argv[2], "stage": sys.argv[3], "streams": int(sys.argv[4]), "profile_sha256": sys.argv[5]}
workload = summary.get("workload") if isinstance(summary.get("workload"), dict) else {}
actual = {"run_id": summary.get("run_id"), "stage": workload.get("stage"), "streams": workload.get("streams"), "profile_sha256": workload.get("profile_sha256")}
if actual != expected:
    raise SystemExit(f"ERROR: summary provenance mismatch: expected {expected}, observed {actual}")
for key in ("schema_version", "timestamps", "hardware", "sources", "durations", "metrics", "raw_metrics", "errors", "acceptance"):
    if key not in summary:
        raise SystemExit(f"ERROR: summary.json missing required section: {key}")
if not isinstance(summary["raw_metrics"], list) or not summary["raw_metrics"]:
    raise SystemExit("ERROR: summary.json must link nonempty raw_metrics evidence")
if not isinstance(summary["metrics"], dict) or not isinstance(summary["errors"], list):
    raise SystemExit("ERROR: metrics must be an object and errors must be an array")
try:
    import jsonschema  # type: ignore
except ImportError:
    print("WARNING: jsonschema is unavailable; performed structural/provenance checks only, not full schema validation")
else:
    schema_path = out.parent.parent.parent / "scripts" / "benchmark" / "summary.schema.json"
    jsonschema.validate(summary, json.loads(schema_path.read_text(encoding="utf-8")))
print(f"Benchmark evidence structure validated: {summary_path}")
print("Acceptance remains the runner/report's evidence-backed decision; this wrapper does not override it.")
PY

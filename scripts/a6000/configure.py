"""Generate (or check) the RTX A6000 workstation profile from the upstream configuration.

The profile is derived, never hand-edited:

* ``configs/a6000/*.yaml``            copies of ``configs/*.yaml`` with the overrides below;
* ``perception/deepstream/a6000/*.txt`` nvinfer configs pointing at the A6000 (sm86) engines.

Overrides (measured on the RTX A6000, reports/a6000/optimization-receipt.json):

* Engines: TensorRT engines built on the A6000 (``scripts/a6000/build-engines.sh``). RT-DETR uses an
  FP16 engine: 2.4 ms/frame vs 5.1 ms FP32, and it reproduces the FP32 boxes on the demo clip
  (99.4 % matched at IoU >= 0.5, mean IoU 0.994).
* Detector: RT-DETR is selected (``candidate_evaluation``). On the crowded demo clip it tracks ~68
  people per frame where TrafficCamNet tracks ~17. It stays labelled an unaccepted candidate: no
  human-reviewed accuracy evaluation exists.
* Replay: ``cam-01`` loops its clip (``loop: true``), so the demo stays live until an operator stop.
* Batched inference (RT-DETR): a dynamic-batch engine (batch 1-8, built for 4) from the dynamic-batch
  re-export of the same checkpoint (scripts/rt-detr-candidate/export_onnx_dynamic.py), with its own infer
  config, used by pipelines shared by 2-8 cameras (runtime.yaml replay.cameras_per_pipeline). Raw TensorRT:
  573 images/s at batch 4 vs 329 at batch 1; in the pipeline 37 % less GPU per frame. Its config leaves
  out output-tensor-meta (no application code reads raw tensors).

Usage::

    python scripts/a6000/configure.py generate   # after building engines; pins their SHA-256
    python scripts/a6000/configure.py check      # exit 1 if the committed profile has drifted
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE_CONFIGS = ROOT / 'configs'
PROFILE_CONFIGS = ROOT / 'configs' / 'a6000'
PROFILE_INFER = ROOT / 'perception' / 'deepstream' / 'a6000'
HEADER = ('# GENERATED by scripts/a6000/configure.py from configs/{name} for the RTX A6000 (sm86) profile.\n'
          '# Do not edit: change configs/{name} or the generator, then run `configure.py generate`.\n')

SELECTED_MODEL = 'rt-detr-person-candidate'
LOOP_CAMERAS = {'cam-01'}
# model id -> (engine path, precision, convert the infer config from strongly-typed FP32 to FP16)
ENGINES = {
    'trafficcamnet-smoke': ('./models/trafficcamnet-smoke/resnet18_trafficcamnet_pruned_fp16_sm86.engine', 'FP16', False),
    'rt-detr-person-candidate': ('./models/rt-detr-person-candidate/rt_detr_r18vd_raw_fp16_sm86.engine', 'FP16', True),
    'rf-detr-person-candidate': ('./models/rf-detr-person-candidate/rf_detr_small_1080p_rgb01_fp32_sm86.engine', 'FP32', False),
}
# model id -> (dynamic-batch ONNX, engine built from it, maximum batch of its optimization profile)
BATCHED = {
    'rt-detr-person-candidate': ('./models/rt-detr-person-candidate/rt_detr_r18vd_raw_dynbatch.onnx',
                                 './models/rt-detr-person-candidate/rt_detr_r18vd_raw_dynbatch_b1-8_fp16_sm86.engine', 8),
}
SELECTION_MODES = {'provisional_smoke': 'provisional_smoke', 'candidate_unaccepted': 'candidate_evaluation',
                   'accepted': 'evaluated_baseline'}


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def file_digest(path: Path) -> str:
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def infer_config(original: str, engine: str, fp16: bool) -> bytes:
    lines = [f'# GENERATED by scripts/a6000/configure.py for the RTX A6000 (sm86) profile; do not edit.']
    if fp16:
        lines.append('# FP16 engine (trtexec --fp16) from the same ONNX; matches the FP32 boxes on the demo clip '
                     '(99.4 % at IoU>=0.5, mean IoU 0.994) at 2.1x the speed.')
    for line in original.splitlines():
        if line.startswith('model-engine-file='):
            line = f'model-engine-file=/workspace/{engine.removeprefix("./")}'
        elif fp16 and line.startswith('network-mode='):
            line = 'network-mode=2'
        elif fp16 and line.startswith('strongly-typed='):
            line = 'strongly-typed=0'
        lines.append(line)
    return ('\n'.join(lines) + '\n').encode('utf-8')


def batched_infer_config(single: bytes, onnx: str, engine: str, max_batch: int) -> bytes:
    lines = ['# GENERATED by scripts/a6000/configure.py for the RTX A6000 (sm86) profile; do not edit.',
             f'# Dynamic-batch engine (batch 1-{max_batch}) for pipelines shared by several cameras; the extractor sets the '
             'batch-size to the camera count. Same checkpoint and preprocessing as the batch-1 config.']
    for line in single.decode('utf-8').splitlines():
        if line.startswith('# GENERATED') or line.startswith('# FP16 engine'):
            continue
        if line.startswith('onnx-file='):
            line = f'onnx-file=/workspace/{onnx.removeprefix("./")}'
        elif line.startswith('model-engine-file='):
            line = f'model-engine-file=/workspace/{engine.removeprefix("./")}'
        elif line.startswith('batch-size='):
            line = f'batch-size={max_batch}'
        elif line.startswith('output-tensor-meta='):
            line = 'output-tensor-meta=0'
        lines.append(line)
    return ('\n'.join(lines) + '\n').encode('utf-8')


def dump(document: dict, name: str) -> bytes:
    return (HEADER.format(name=name) + yaml.safe_dump(document, sort_keys=False)).encode('utf-8')


def build() -> dict[Path, bytes]:
    """Every generated file and its exact bytes. Engines must exist (their SHA-256 is pinned)."""
    outputs: dict[Path, bytes] = {}
    for source in sorted(SOURCE_CONFIGS.glob('*.yaml')):
        document = yaml.safe_load(source.read_text(encoding='utf-8'))
        if source.name == 'cameras.yaml':
            for camera in document['cameras']:
                if camera['id'] in LOOP_CAMERAS and camera['source_type'] == 'file':
                    camera['loop'] = True
        elif source.name == 'models.yaml':
            for model in document['models']:
                engine, precision, fp16 = ENGINES[model['id']]
                engine_path = ROOT / engine
                if not engine_path.is_file() or engine_path.stat().st_size < 1024:
                    raise SystemExit(f'A6000 engine missing (build it with scripts/a6000/build-engines.sh, or '
                                     f'git lfs pull): {engine}')
                profile = model['runtime_profile']
                original = (ROOT / profile['infer_config_path']).read_text(encoding='utf-8')
                infer_path = PROFILE_INFER / f"{model['id']}.txt"
                infer_bytes = infer_config(original, engine, fp16)
                outputs[infer_path] = infer_bytes
                model['engine_path'] = engine
                model['engine_sha256'] = file_digest(engine_path)
                model['precision'] = precision
                profile['infer_config_path'] = './' + infer_path.relative_to(ROOT).as_posix()
                profile['infer_config_sha256'] = digest(infer_bytes)
                if fp16:
                    profile['preprocessing'] += ' RTX A6000 profile: FP16 engine, validated against FP32 on the demo clip.'
                if model['id'] in BATCHED:
                    onnx, batched_engine, max_batch = BATCHED[model['id']]
                    for path in (ROOT / onnx, ROOT / batched_engine):
                        if not path.is_file() or path.stat().st_size < 1024:
                            raise SystemExit(f'A6000 batched artifact missing (scripts/rt-detr-candidate/'
                                             f'export_onnx_dynamic.py, build-engines.sh, or git lfs pull): {path}')
                    batched_path = PROFILE_INFER / f"{model['id']}-batched.txt"
                    batched_bytes = batched_infer_config(infer_bytes, onnx, batched_engine, max_batch)
                    outputs[batched_path] = batched_bytes
                    profile['batched'] = {
                        'infer_config_path': './' + batched_path.relative_to(ROOT).as_posix(),
                        'infer_config_sha256': digest(batched_bytes),
                        'onnx_path': onnx, 'onnx_sha256': file_digest(ROOT / onnx),
                        'engine_path': batched_engine, 'engine_sha256': file_digest(ROOT / batched_engine),
                        'max_batch_size': max_batch,
                    }
            selected = next(model for model in document['models'] if model['id'] == SELECTED_MODEL)
            document['selected_model'] = SELECTED_MODEL
            document['selection_mode'] = SELECTION_MODES[selected['acceptance']]
        outputs[PROFILE_CONFIGS / source.name] = dump(document, source.name)
    return outputs


def generate() -> None:
    outputs = build()
    for path, data in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    for stale in [*PROFILE_CONFIGS.glob('*.yaml'), *PROFILE_INFER.glob('*.txt')]:
        if stale not in outputs:
            stale.unlink()
    for path in outputs:
        print(path.relative_to(ROOT).as_posix())


def check() -> int:
    outputs = build()
    drift = [path.relative_to(ROOT).as_posix() for path, data in outputs.items()
             if not path.is_file() or path.read_bytes() != data]
    extra = [path.relative_to(ROOT).as_posix() for path in [*PROFILE_CONFIGS.glob('*.yaml'), *PROFILE_INFER.glob('*.txt')]
             if path not in outputs]
    if drift or extra:
        print('A6000 profile is out of date; run: python scripts/a6000/configure.py generate')
        for item in drift:
            print(f'  differs: {item}')
        for item in extra:
            print(f'  not generated: {item}')
        return 1
    print('A6000 profile matches configs/ and the engines.')
    return 0


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('mode', choices=('generate', 'check'))
    arguments = parser.parse_args()
    if arguments.mode == 'generate':
        generate()
    else:
        sys.exit(check())
